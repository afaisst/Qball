#!/usr/bin/env node
// Qball — pack the paintings for the 3D room into js/art.js.
//
// Pages opened straight from disk (file://) can't use separate image files as WebGL textures, so the images are
// embedded in a script. Source: assets/art/*.jpg (or .png) plus assets/art/paintings.json for titles and credits.
//
// To add your own paintings (e.g. works by Rainer Oberhänsli, with the artist's permission):
//   1. put the image files in assets/art/, e.g. oberhaensli-1.jpg and oberhaensli-2.jpg
//      (files whose name starts with "oberhaensli" go into the two frames reserved for his work)
//   2. optionally add an entry to assets/art/paintings.json: { "id": "oberhaensli-1", "artist": "...", "title": "...", "year": "..." }
//   3. run:  node tools/embed-art.js
// Keep the images small (about 700 px on the long side) so the page stays quick to load.
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'art'), out = path.join(__dirname, '..', 'js', 'art.js');
const metaFile = path.join(dir, 'paintings.json');
const meta = fs.existsSync(metaFile) ? JSON.parse(fs.readFileSync(metaFile, 'utf8')) : [];
const byId = Object.fromEntries(meta.map(m => [m.id, m]));
const files = fs.readdirSync(dir).filter(f => /\.(jpe?g|png)$/i.test(f)).sort();
const list = [];
for (const f of files) {
  const id = f.replace(/\.[^.]+$/, ''), m = byId[id] || { id, artist: '', title: id.replace(/[-_]+/g, ' '), year: '' };
  const mime = /\.png$/i.test(f) ? 'image/png' : 'image/jpeg';
  const data = `data:${mime};base64,` + fs.readFileSync(path.join(dir, f)).toString('base64');
  list.push(Object.assign({}, m, { id, data }));
  console.log(`  ${id}  (${Math.round(fs.statSync(path.join(dir, f)).size / 1024)} KB)  ${m.artist} — ${m.title}`);
}
const js = '// Qball — paintings for the 3D room. GENERATED by tools/embed-art.js from assets/art/ — edit those, not this file.\n'
  + 'window.QB = window.QB || {};\nQB.ART = ' + JSON.stringify(list, null, 1) + ';\n';
fs.writeFileSync(out, js);
console.log(`wrote ${path.relative(process.cwd(), out)} (${list.length} paintings, ${Math.round(js.length / 1024)} KB)`);
